"""Maintained FreeCAD working document: cad/out/<variant>/ARC_Arm_<variant>.FCStd, generated from the model.

The model's source of truth is the code + TOML in cad/; this document is the openable view of it, rebuilt whenever
the design changes (it records cad-evidence, so tools/quick_check.py shows it FRESH/STALE like every other check).
  - one group per moving body (GROUND, UPPER, ..., ROD2, LEVEL, GRIPPER, HEAD, jaws/links), parts as Part::Feature;
  - posed at STOW (POSE env var to change), jaw at that pose;
  - colours by material when run inside the FreeCAD GUI (view providers only exist there); headless runs write the
    same geometry uncoloured. Any variant (unlike the release generator build_assembly.py).

GUI (coloured):   exec(open(r"<repo>/cad/tools/working_doc.py").read())       (or via the MCP execute_code tool)
headless:         GRIP=FOURBAR freecadcmd cad/tools/working_doc.py
"""
import os
import sys

CAD = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) if "__file__" in globals() else \
    r"C:\Users\ryanh\light_weight_arm\cad"
if CAD not in sys.path:
    sys.path.insert(0, CAD)
import FreeCAD as App  # noqa: E402

RGB = {"cf": (0.12, 0.12, 0.13), "pla": (0.90, 0.32, 0.06), "alu": (0.80, 0.81, 0.84), "steel": (0.30, 0.31, 0.33),
       "motor": (0.08, 0.08, 0.09), "pad": (0.12, 0.35, 0.85), "brass": (0.85, 0.65, 0.30), "pcb": (0.05, 0.30, 0.10),
       "pom": (0.92, 0.91, 0.86)}


def build(pose=None):
    if App.GuiUp:                         # pick up edits in a long-running GUI session
        import arm
        import iface
        iface._CACHE.clear()
        arm.reload_all()
    import arm_model as M
    import params
    pose = pose or os.environ.get("POSE", "STOW")
    var = M.GRIP.lower()
    name = "ARC_Arm_%s" % M.GRIP.capitalize()
    path = os.path.join(CAD, "out", var, name + ".FCStd")
    if name in App.listDocuments():
        App.closeDocument(name)
    doc = App.newDocument(name)
    doc.Comment = "Generated by cad/tools/working_doc.py from the cad/ model (%s, pose %s). Do not edit: rebuild." % (M.GRIP, pose)
    bodies = M.build_bodies()
    q, jaw = M.pose_q(pose)
    groups, n = {}, 0
    for bname, p, s in M.placed(bodies, *q, jaw=jaw, which="vis"):
        if s.isNull():
            continue
        grp = groups.get(bname) or groups.setdefault(bname, doc.addObject("App::DocumentObjectGroup", bname))
        o = doc.addObject("Part::Feature", p.name.replace("-", "_"))
        o.Shape = s
        o.Label = p.name
        grp.addObject(o)
        if App.GuiUp and o.ViewObject is not None:
            o.ViewObject.ShapeColor = RGB.get(p.color, (0.5, 0.5, 0.5))
        n += 1
    doc.recompute()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    doc.saveAs(path)
    if App.GuiUp:
        import FreeCADGui as Gui
        Gui.activeDocument().activeView().viewIsometric()
        Gui.SendMsgToActiveView("ViewFit")
    note = "%s: %d parts in %d body groups at %s, %s (%.1f MB)" % (
        os.path.basename(path), n, len(groups), pose, "coloured" if App.GuiUp else "uncoloured (headless)",
        os.path.getsize(path) / 1e6)
    params.record("working_doc", "PASS", files=[path], note=note)   # absolute: GUI cwd is System32
    print("WORKING_DOC", note)
    return path


build()
