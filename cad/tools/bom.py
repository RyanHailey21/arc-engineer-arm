# -*- coding: utf-8 -*-
"""
Variant bill of materials (does not touch the released rev A cad/fab/BOM.csv):
    set GRIP=FOURBAR & freecadcmd cad/tools/bom.py      -> cad/out/<variant>/BOM.csv + BOM.md + evidence record
Purchased parts are grouped by catalogue key (data/catalogue.toml: description, source, what to verify); custom
parts are listed one per line with material and process.  Flags any purchased part with no source.
"""
import csv
import os
import sys

CAD = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) if "__file__" in globals() else r"C:\Users\ryanh\light_weight_arm\cad"
sys.path.insert(0, CAD)
import arm_model as M  # noqa: E402
import params          # noqa: E402

SOURCE_FREE = {"BHCS", "SHCS", "CSK", "INSERT", "SETSCREW", "ECLIP", "DOWEL"}      # generic hardware: any ISO supplier


def procurement():
    """Rev A supplier records (cad/fab/procurement.csv, all VERIFIED) keyed by item name."""
    p = os.path.join(CAD, "fab", "procurement.csv")
    return list(csv.DictReader(open(p, encoding="utf-8"))) if os.path.exists(p) else []


def supplier(key, proc):
    exact = [r for r in proc if r["item"] == key]
    near = exact or [r for r in proc if key.upper() in r["item"].upper()]
    if not near:
        return ""
    r = near[0]
    more = " (+%d sizes, see fab/procurement.csv)" % (len(near) - 1) if len(near) > 1 else ""
    return "%s %s [%s]%s" % (r["vendor"], r["part_number"], r["status"], more)


def main():
    bodies = M.build_bodies()
    proc = procurement()
    cat, custom = {}, []
    for bn, ps in bodies.items():
        for p in ps:
            m = M.part_mass_g(p)
            if p.kind == "CAT":
                e = cat.setdefault(p.src, dict(qty=0, mass=0.0, bodies=set()))
                e["qty"] += 0 if "rotor" in p.name else 1        # split motors: the rotor part is the same motor
                e["mass"] += m
                e["bodies"].add(bn)
            else:
                custom.append((bn, p.name, p.kind, p.src.replace("custom: ", ""), m))
    out = params.out_dir()
    rows, unsourced = [], []
    for k, e in sorted(cat.items()):
        c = M.CAT.get(k, {})
        src = c.get("src", "") or supplier(k, proc)
        if not src and k not in SOURCE_FREE:
            unsourced.append(k)
        rows.append(["purchased", k, e["qty"], round(e["mass"], 1), c.get("desc", ""), src or ("ISO standard, any supplier" if k in SOURCE_FREE else ""),
                     c.get("verify", ""), " ".join(sorted(e["bodies"]))])
    for bn, nm, kind, how, m in custom:
        rows.append(["custom", nm, 1, round(m, 1), how, "make (%s)" % kind, "", bn])
    head = ["type", "item", "qty", "mass_g", "description", "source", "verify", "bodies"]
    with open(os.path.join(out, "BOM.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(head)
        w.writerows(rows)
    md = ["# Bill of materials - variant %s" % M.GRIP, "",
          "%d purchased line items (%d pieces), %d custom parts, %.0f g total. Generated by cad/tools/bom.py." % (
              len(cat), sum(e["qty"] for e in cat.values()), len(custom), sum(r[3] for r in rows)), "",
          "| Item | Qty | Mass (g) | Description | Source | Verify |", "|---|---|---|---|---|---|"]
    for r in rows:
        if r[0] == "purchased":
            md.append("| %s | %d | %.1f | %s | %s | %s |" % (r[1], r[2], r[3], r[4].replace("|", "/"), r[5].replace("|", "/"), r[6].replace("|", "/")))
    md += ["", "Custom parts: see BOM.csv (%d lines)." % len(custom)]
    open(os.path.join(out, "BOM.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    st = "FAIL" if unsourced else "PASS"
    params.record("bom", st, [os.path.join(out, "BOM.csv"), os.path.join(out, "BOM.md")],
                  "%d purchased items, unsourced: %s" % (len(cat), ", ".join(unsourced) or "none"))
    print("BOM %s: %d purchased items (%d pcs), %d custom parts; unsourced: %s" % (
        M.GRIP, len(cat), sum(e["qty"] for e in cat.values()), len(custom), ", ".join(unsourced) or "none"))


main()
